package integration

import (
	"testing"

	"github.com/davidklassen/winch/internal/module"
	"github.com/davidklassen/winch/internal/vmtest"
)

// spec: Modules/file, dir, link
func TestDirModule(t *testing.T) {
	t.Parallel()
	vm := lab.StartVM(t, "dir")
	attrs := "owner root, group root, mode 0755"
	reset := "grep -o ' /tmp/w/[^ ]*' /proc/self/mounts | sort -r | xargs -r umount\nfor d in /tmp/w /tmp/wsrc; do [ ! -e $d ] || find $d \\( -type f -o -type d \\) -exec chattr -ia {} +; done\nrm -rf /tmp/w /tmp/wsrc && mkdir /tmp/w"
	vmtest.RunCases(t, vm, "dir", reset, []vmtest.Case{
		{
			Name:      "create with parents",
			Args:      &module.Dir{Path: "/tmp/w/a/b"},
			Want:      module.Result{Status: module.Change, Action: module.Create, Changes: []string{"create directory /tmp/w/a (owner root, group root, mode 0755)", attrs}},
			Unchanged: `[ ! -e /tmp/w/a ]`,
			After:     `[ "$(stat -c '%F %U %G %a' /tmp/w/a /tmp/w/a/b | sort -u)" = "directory root root 755" ]`,
		},
		{
			Name:  "ok",
			Setup: `mkdir /tmp/w/d`,
			Args:  &module.Dir{Path: "/tmp/w/d"},
			Want:  module.Result{Status: module.OK},
		},
		{
			Name:      "owner and mode",
			Setup:     `mkdir /tmp/w/d && chown admin:admin /tmp/w/d && chmod 700 /tmp/w/d`,
			Args:      &module.Dir{Path: "/tmp/w/d"},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"owner admin → root", "group admin → root", "mode 0700 → 0755"}},
			Unchanged: `[ "$(stat -c '%U %G %a' /tmp/w/d)" = "admin admin 700" ]`,
			After:     `[ "$(stat -c '%U %G %a' /tmp/w/d)" = "root root 755" ]`,
		},
		{
			Name:  "given owner group mode",
			Args:  &module.Dir{Path: "/tmp/w/d", Owner: "admin", Group: "adm", Mode: "2750"},
			Want:  module.Result{Status: module.Change, Action: module.Create, Changes: []string{"owner admin, group adm, mode 2750"}},
			After: `[ "$(stat -c '%U %G %a' /tmp/w/d)" = "admin adm 2750" ]`,
		},
		{
			Name:  "numeric IDs that no user has",
			Setup: `! getent passwd 4242 && ! getent group 4242`,
			Args:  &module.Dir{Path: "/tmp/w/d", Owner: "4242", Group: "4242"},
			Want:  module.Result{Status: module.Change, Action: module.Create, Changes: []string{"owner 4242, group 4242, mode 0755"}},
			After: `[ "$(stat -c '%u %g' /tmp/w/d)" = "4242 4242" ]`,
		},
		{
			Name:  "numeric IDs of the current owner",
			Setup: `mkdir /tmp/w/d`,
			Args:  &module.Dir{Path: "/tmp/w/d", Owner: "0", Group: "0"},
			Want:  module.Result{Status: module.OK},
		},
		{
			Name:      "numeric IDs to names",
			Setup:     `mkdir /tmp/w/d && chown 4242:4242 /tmp/w/d`,
			Args:      &module.Dir{Path: "/tmp/w/d"},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"owner 4242 → root", "group 4242 → root"}},
			Unchanged: `[ "$(stat -c '%u %g' /tmp/w/d)" = "4242 4242" ]`,
			After:     `[ "$(stat -c '%U %G' /tmp/w/d)" = "root root" ]`,
		},
		{
			Name:      "names to numeric IDs",
			Setup:     `mkdir /tmp/w/d`,
			Args:      &module.Dir{Path: "/tmp/w/d", Owner: "4242", Group: "4242"},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"owner root → 4242", "group root → 4242"}},
			Unchanged: `[ "$(stat -c '%U %G' /tmp/w/d)" = "root root" ]`,
			After:     `[ "$(stat -c '%u %g' /tmp/w/d)" = "4242 4242" ]`,
		},
		{
			Name:      "setgid mode stays after a change of group",
			Setup:     `mkdir /tmp/w/d && chgrp admin /tmp/w/d && chmod 2775 /tmp/w/d`,
			Args:      &module.Dir{Path: "/tmp/w/d", Mode: "2775"},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"group admin → root"}},
			Unchanged: `[ "$(stat -c '%G %a' /tmp/w/d)" = "admin 2775" ]`,
			After:     `[ "$(stat -c '%U %G %a' /tmp/w/d)" = "root root 2775" ]`,
		},
		{
			Name:  "parents get the default owner and mode",
			Args:  &module.Dir{Path: "/tmp/w/a/b", Owner: "admin", Mode: "0700"},
			Want:  module.Result{Status: module.Change, Action: module.Create, Changes: []string{"create directory /tmp/w/a (owner root, group root, mode 0755)", "owner admin, group root, mode 0700"}},
			After: `[ "$(stat -c '%U %G %a' /tmp/w/a)" = "root root 755" ] && [ "$(stat -c '%U %G %a' /tmp/w/a/b)" = "admin root 700" ]`,
		},
		{
			Name:         "owner that does not exist yet",
			Args:         &module.Dir{Path: "/tmp/w/d", Owner: "later"},
			Want:         module.Result{Status: module.Change, Action: module.Create, Changes: []string{`owner later, group root, mode 0755; user "later" does not exist yet`}},
			WantApplyErr: `user "later" does not exist`,
		},
		{
			Name:    "absent on a symbolic link fails",
			Setup:   `mkdir /tmp/w/d && ln -s /tmp/w/d /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l", Absent: true},
			WantErr: "/tmp/w/l is a symbolic link, not a directory",
		},
		{
			Name:      "absent removes the content",
			Setup:     `mkdir -p /tmp/w/d/x && touch /tmp/w/d/x/f`,
			Args:      &module.Dir{Path: "/tmp/w/d", Absent: true},
			Want:      module.Result{Status: module.Change, Action: module.Remove, Changes: []string{"remove its content"}},
			Unchanged: `[ -f /tmp/w/d/x/f ]`,
			After:     `[ ! -e /tmp/w/d ]`,
		},
		{
			Name:  "absent removes an empty directory",
			Setup: `mkdir /tmp/w/d`,
			Args:  &module.Dir{Path: "/tmp/w/d", Absent: true},
			Want:  module.Result{Status: module.Change, Action: module.Remove},
			After: `[ ! -e /tmp/w/d ]`,
		},
		{
			Name:    "absent on a tree with a mount point fails",
			Setup:   `mkdir -p /tmp/w/d/x/m && mount -t tmpfs tmpfs /tmp/w/d/x/m && touch /tmp/w/d/x/m/f`,
			Args:    &module.Dir{Path: "/tmp/w/d", Absent: true},
			WantErr: "/tmp/w/d/x/m is a mount point",
		},
		{
			Name:    "absent on a mount point fails",
			Setup:   `mkdir /tmp/w/d && mount -t tmpfs tmpfs /tmp/w/d && touch /tmp/w/d/f`,
			Args:    &module.Dir{Path: "/tmp/w/d", Absent: true},
			WantErr: "/tmp/w/d is a mount point",
		},
		{
			Name:    "absent on a tree with a bind mount fails",
			Setup:   `mkdir -p /tmp/wsrc /tmp/w/d/m && touch /tmp/wsrc/f && mount --bind /tmp/wsrc /tmp/w/d/m`,
			Args:    &module.Dir{Path: "/tmp/w/d", Absent: true},
			WantErr: "/tmp/w/d/m is a mount point",
		},
		{
			Name:  "absent below a mount point works",
			Setup: `mkdir -p /tmp/w/p && mount -t tmpfs tmpfs /tmp/w/p && mkdir /tmp/w/p/d`,
			Args:  &module.Dir{Path: "/tmp/w/p/d", Absent: true},
			Want:  module.Result{Status: module.Change, Action: module.Remove},
			After: `[ -d /tmp/w/p ] && [ ! -e /tmp/w/p/d ]`,
		},
		{
			Name:         "a mount put in the tree before apply stays",
			Setup:        `mkdir -p /tmp/w/d/m`,
			Args:         &module.Dir{Path: "/tmp/w/d", Absent: true},
			Want:         module.Result{Status: module.Change, Action: module.Remove, Changes: []string{"remove its content"}},
			BeforeApply:  `mount -t tmpfs tmpfs /tmp/w/d/m && touch /tmp/w/d/m/f`,
			WantApplyErr: "/tmp/w/d/m is a mount point",
			After:        `[ -f /tmp/w/d/m/f ]`,
		},
		{
			Name: "absent when missing is ok",
			Args: &module.Dir{Path: "/tmp/w/d", Absent: true},
			Want: module.Result{Status: module.OK},
		},
		{
			Name:  "absent when a parent is a file is ok",
			Setup: `touch /tmp/w/f`,
			Args:  &module.Dir{Path: "/tmp/w/f/d", Absent: true},
			Want:  module.Result{Status: module.OK},
		},
		{
			Name:    "absent on a tree with an immutable file fails",
			Setup:   `mkdir -p /tmp/w/d/a /tmp/w/d/b && touch /tmp/w/d/a/1 /tmp/w/d/b/2 /tmp/w/d/c && chattr +i /tmp/w/d/b/2`,
			Args:    &module.Dir{Path: "/tmp/w/d", Absent: true},
			WantErr: "/tmp/w/d/b/2 is immutable; chattr -i changes it",
		},
		{
			Name:    "absent on an append-only directory fails",
			Setup:   `mkdir -p /tmp/w/d && touch /tmp/w/d/f && chattr +a /tmp/w/d`,
			Args:    &module.Dir{Path: "/tmp/w/d", Absent: true},
			WantErr: "/tmp/w/d is append-only; chattr -a changes it",
		},
		{
			Name:  "absent on a tree with a link to an immutable file works",
			Setup: `mkdir /tmp/w/d && touch /tmp/wsrc && chattr +i /tmp/wsrc && ln -s /tmp/wsrc /tmp/w/d/l`,
			Args:  &module.Dir{Path: "/tmp/w/d", Absent: true},
			Want:  module.Result{Status: module.Change, Action: module.Remove, Changes: []string{"remove its content"}},
			After: `[ ! -e /tmp/w/d ] && [ -f /tmp/wsrc ]`,
		},
		{
			Name:    "replace an immutable file fails",
			Setup:   `touch /tmp/w/f && chattr +i /tmp/w/f`,
			Args:    &module.Dir{Path: "/tmp/w/f", Replace: true},
			WantErr: "/tmp/w/f is immutable; chattr -i changes it",
		},
		{
			Name:  "an immutable directory that is already right is ok",
			Setup: `mkdir /tmp/w/d && chattr +i /tmp/w/d`,
			Args:  &module.Dir{Path: "/tmp/w/d"},
			Want:  module.Result{Status: module.OK},
		},
		{
			Name:    "an immutable directory fails",
			Setup:   `mkdir /tmp/w/d && chmod 700 /tmp/w/d && chattr +i /tmp/w/d`,
			Args:    &module.Dir{Path: "/tmp/w/d"},
			WantErr: "/tmp/w/d is immutable; chattr -i changes it",
		},
		{
			Name:    "an immutable directory behind a link fails",
			Setup:   `mkdir /tmp/wsrc && chmod 700 /tmp/wsrc && chattr +i /tmp/wsrc && ln -s /tmp/wsrc /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is immutable; chattr -i changes it",
		},
		{
			Name:    "absent on a file fails",
			Setup:   `touch /tmp/w/f`,
			Args:    &module.Dir{Path: "/tmp/w/f", Absent: true},
			WantErr: "/tmp/w/f is a file, not a directory",
		},
		{
			Name:    "a file at path fails and names replace",
			Setup:   `touch /tmp/w/f`,
			Args:    &module.Dir{Path: "/tmp/w/f"},
			WantErr: "/tmp/w/f is a file; add replace: true to remove it",
		},
		{
			Name:      "replace a file",
			Setup:     `echo keep > /tmp/w/f`,
			Args:      &module.Dir{Path: "/tmp/w/f", Replace: true},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"remove file /tmp/w/f", attrs}},
			Unchanged: `[ "$(cat /tmp/w/f)" = keep ]`,
			After:     `[ "$(stat -c '%F %U %G %a' /tmp/w/f)" = "directory root root 755" ]`,
		},
		{
			Name:  "/var/run follows the link to /run",
			Args:  &module.Dir{Path: "/var/run"},
			Want:  module.Result{Status: module.OK},
			After: `[ "$(readlink /var/run)" = /run ]`,
		},
		{
			Name:      "a mode on a followed link changes the target",
			Setup:     `mkdir /tmp/w/t && chown admin /tmp/w/t && chmod 700 /tmp/w/t && ln -s t /tmp/w/l`,
			Args:      &module.Dir{Path: "/tmp/w/l"},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"owner admin → root", "mode 0700 → 0755"}, Link: "t"},
			Unchanged: `[ "$(stat -c '%U %a' /tmp/w/t)" = "admin 700" ]`,
			After:     `[ "$(readlink /tmp/w/l)" = t ] && [ "$(stat -c '%U %G %a' /tmp/w/t)" = "root root 755" ]`,
		},
		{
			Name:    "a link to a file fails",
			Setup:   `touch /tmp/w/f && ln -s f /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link to a file; add replace: true to remove it",
		},
		{
			Name:    "a link to a link to a named pipe fails",
			Setup:   `mkfifo /tmp/w/p && ln -s p /tmp/w/m && ln -s m /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link to a named pipe; add replace: true to remove it",
		},
		{
			Name:    "a broken link fails",
			Setup:   `ln -s missing /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link to a missing target; add replace: true to remove it",
		},
		{
			Name:    "a link to a file with a trailing slash fails",
			Setup:   `touch /tmp/w/f && ln -s f/ /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link to a file; add replace: true to remove it",
		},
		{
			Name:    "a link loop fails",
			Setup:   `ln -s m /tmp/w/l && ln -s l /tmp/w/m`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link with too many levels of symbolic links; add replace: true to remove it",
		},
		{
			Name:    "a link to a path below a file fails",
			Setup:   `touch /tmp/w/f && ln -s f/x /tmp/w/l`,
			Args:    &module.Dir{Path: "/tmp/w/l"},
			WantErr: "/tmp/w/l is a symbolic link to a missing target; add replace: true to remove it",
		},
		{
			Name:    "a link at path in /tmp fails",
			Setup:   `rm -f /tmp/wl && ln -s /tmp/w /tmp/wl`,
			Args:    &module.Dir{Path: "/tmp/wl"},
			WantErr: "/tmp/wl is a symbolic link in /tmp, which a user other than root can write",
		},
		{
			Name:      "replace a link to a directory",
			Setup:     `mkdir /tmp/w/t && touch /tmp/w/t/f && ln -s /tmp/w/t /tmp/w/l`,
			Args:      &module.Dir{Path: "/tmp/w/l", Replace: true},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"replace the symbolic link to /tmp/w/t", attrs}},
			Unchanged: `[ -L /tmp/w/l ]`,
			After:     `[ -d /tmp/w/l ] && [ ! -L /tmp/w/l ] && [ -f /tmp/w/t/f ]`,
		},
		{
			Name:      "replace a link to a file",
			Setup:     `touch /tmp/w/f && ln -s f /tmp/w/l`,
			Args:      &module.Dir{Path: "/tmp/w/l", Replace: true},
			Want:      module.Result{Status: module.Change, Action: module.Modify, Changes: []string{"replace the symbolic link to f", attrs}},
			Unchanged: `[ -L /tmp/w/l ]`,
			After:     `[ -d /tmp/w/l ] && [ ! -L /tmp/w/l ] && [ -f /tmp/w/f ]`,
		},
		{
			Name:    "a FIFO at path fails",
			Setup:   "mkfifo /tmp/w/p",
			Args:    &module.Dir{Path: "/tmp/w/p"},
			WantErr: "/tmp/w/p is a named pipe, not a directory",
		},
		{
			Name:    "a socket at path fails",
			Setup:   mksock,
			Args:    &module.Dir{Path: "/tmp/w/s", Absent: true},
			WantErr: "/tmp/w/s is a socket, not a directory",
		},
		{
			Name:    "a file as parent fails",
			Setup:   `touch /tmp/w/f`,
			Args:    &module.Dir{Path: "/tmp/w/f/d"},
			WantErr: "/tmp/w/f is a file, not a directory",
		},
		{
			Name:    "a link in a user's home fails",
			Setup:   `rm -rf /home/admin/w && ln -s /tmp/w /home/admin/w`,
			Args:    &module.Dir{Path: "/home/admin/w/d"},
			WantErr: "/home/admin/w is a symbolic link in /home/admin, which a user other than root can write",
		},
		{
			Name:         "a link put in a user's home before apply fails",
			Setup:        `rm -rf /home/admin/w && mkdir /home/admin/w && chown admin: /home/admin/w`,
			Args:         &module.Dir{Path: "/home/admin/w/d"},
			Want:         module.Result{Status: module.Change, Action: module.Create, Changes: []string{attrs}},
			BeforeApply:  `rm -rf /home/admin/w && ln -s /tmp/w /home/admin/w`,
			WantApplyErr: "/home/admin/w is a symbolic link in /home/admin, which a user other than root can write",
			After:        `[ ! -e /tmp/w/d ] && [ ! -L /tmp/w/d ]`,
		},
		{
			Name:    "a link in /tmp fails",
			Setup:   `rm -f /tmp/wl && ln -s /tmp/w /tmp/wl`,
			Args:    &module.Dir{Path: "/tmp/wl/d"},
			WantErr: "/tmp/wl is a symbolic link in /tmp, which a user other than root can write",
		},
		{
			Name:  "a path under /var/run works",
			Setup: `rm -rf /run/w`,
			Args:  &module.Dir{Path: "/var/run/w/d"},
			Want:  module.Result{Status: module.Change, Action: module.Create, Changes: []string{"create directory /var/run/w (owner root, group root, mode 0755)", attrs}},
			After: `[ -d /run/w/d ]`,
		},
		{
			Name:         "absent through a link put in a user's home before apply fails",
			Setup:        `rm -rf /home/admin/w && mkdir -p /home/admin/w/d && chown -R admin: /home/admin/w && mkdir /tmp/w/d`,
			Args:         &module.Dir{Path: "/home/admin/w/d", Absent: true},
			Want:         module.Result{Status: module.Change, Action: module.Remove},
			BeforeApply:  `rm -rf /home/admin/w && ln -s /tmp/w /home/admin/w`,
			WantApplyErr: "/home/admin/w is a symbolic link in /home/admin, which a user other than root can write",
			After:        `[ -d /tmp/w/d ]`,
		},
		{
			Name:  "a path with spaces and shell characters",
			Args:  &module.Dir{Path: oddDir},
			Want:  module.Result{Status: module.Change, Action: module.Create, Changes: []string{attrs}},
			After: "[ -d " + vmtest.Quote(oddDir) + " ] && [ ! -e /tmp/pwn ]",
		},
	})
}
